static const uint8_t *Glyph(uint8_t c, uint8_t *left, uint8_t *width)
{
    if (c < 32 || c > 126)
        c = '?';
    const uint8_t *rows = sans[c - 32];
    uint8_t occupied = 0;
    for (uint8_t y = 0; y < 7; y++)
        occupied |= rows[y];
    *left = 0;
    *width = 2;
    if (occupied)
    {
        while (!(occupied & (16u >> *left)))
            ++*left;
        uint8_t right = 4;
        while (!(occupied & (16u >> right)))
            --right;
        *width = right - *left + 1;
    }
    return rows;
}

uint16_t UI_ClearTextWidth(const char *text, uint8_t count)
{
    uint16_t pixels = 0;
    for (uint8_t n = 0; n < count && text[n]; n++)
    {
        uint8_t left, width;
        Glyph((uint8_t)text[n], &left, &width);
        pixels += width + 1;
    }
    return pixels ? pixels - 1 : 0;
}

void UI_ClearTextLine(uint8_t *line, const char *text, uint8_t left,
                      uint8_t right, bool centered)
{
    if (!line || !text || left >= right || right > 128)
        return;
    const uint16_t available = right - left;
    const uint16_t natural = UI_ClearTextWidth(text, 255);
    uint8_t gap = natural > available ? 0 : 1;
    uint16_t width = natural;
    if (!gap)
        for (uint8_t n = 0; n < 254 && text[n] && text[n + 1]; n++)
            --width;
    uint16_t x = left;
    if (centered && width < available)
        x += (available - width) / 2;
    for (uint8_t n = 0; n < 255 && text[n] && x < right; n++)
    {
        uint8_t first, columns;
        const uint8_t *rows = Glyph((uint8_t)text[n], &first, &columns);
        for (uint8_t column = 0; column < columns && x < right; column++, x++)
            for (uint8_t y = 0; y < 7; y++)
                if (rows[y] & (16u >> (first + column)))
                    line[x] |= 1u << y;
        x += gap;
    }
}

void UI_ClearText(const char *text, uint8_t left, uint8_t right,
                  uint8_t page, bool centered)
{
    if (page < 7)
        UI_ClearTextLine(gFrameBuffer[page], text, left, right, centered);
}
